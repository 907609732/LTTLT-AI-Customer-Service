import { z } from 'zod'
import { randomUUID } from 'node:crypto'
import { readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import type { Product } from '../../src/shared/contracts/backend'
import type { KnowledgeRepository } from './repository'
import type { KnowledgeScope } from '../../src/shared/contracts/knowledge'
import { knowledgeRequire } from './node-loader'
const Papa = knowledgeRequire('papaparse') as {
  parse(
    text: string,
    options: { header: true; skipEmptyLines: string },
  ): { data: Record<string, string>[]; errors: unknown[]; meta: { fields?: string[] } }
  unparse(data: object[], options: { escapeFormulae: boolean }): string
}
const text = (n: number) => z.string().trim().max(n)
export const legacyProductInputSchema = z
  .object({
    storeId: text(64).min(1),
    productId: text(100).min(1),
    title: text(200).min(1),
    description: text(6000).default(''),
    specifications: text(3000).default(''),
    price: text(80).default(''),
    enabled: z.boolean().default(true),
  })
  .strict()
export const legacyProductSchema = legacyProductInputSchema.extend({
  id: z.string().uuid(),
  version: z.number().int().positive(),
  updatedAt: z.number().int().nonnegative(),
})
export const qualitySourceSchema = z
  .object({
    type: z.literal('quality'),
    recordId: z.string().uuid(),
    qualityVersion: z.number().int().nonnegative(),
    storeId: text(64).min(1),
    uid: text(200).min(1),
    messageTs: z.number().finite(),
    savedAt: z.number().finite(),
  })
  .strict()
const intentEntry = z
  .object({
    question: text(1000).min(1),
    keywords: z.array(text(100).min(1)).max(30),
    answer: text(4000).min(1),
    enabled: z.boolean(),
  })
  .strict()
export const legacyIntentInputSchema = z
  .object({
    name: text(100).min(1),
    enabled: z.boolean(),
    storeIds: z.array(text(64).min(1)).max(100),
    productIds: z.array(text(100).min(1)).max(1000),
    entries: z.array(intentEntry).min(1).max(500),
  })
  .strict()
export const legacyIntentSchema = legacyIntentInputSchema.extend({
  id: z.string().uuid(),
  version: z.number().int().positive(),
  updatedAt: z.number().int().nonnegative(),
  source: qualitySourceSchema.optional(),
})
export type LegacyIntentPack = z.infer<typeof legacyIntentSchema>
export const auditQuestion = '【学习来源审计，请保持停用】'
function bump(repo: KnowledgeRepository, key: string) {
  repo.setMetadata(key, String(Number(repo.getMetadata(key) ?? 0) + 1))
}
function review(
  repo: KnowledgeRepository,
  version: ReturnType<KnowledgeRepository['saveDraft']>,
  reason: 'legacy-preserved' | 'manual-correction',
) {
  repo.publishReviewed(
    {
      entryId: version.id,
      expectedDraftRevision: version.revision,
      expectedSourceRevisions: Object.fromEntries(
        version.sourceRefs.map((ref) => [ref.sourceId, ref.revision]),
      ),
    },
    reason,
  )
}
export function ingestLegacyProduct(
  repo: KnowledgeRepository,
  product: Product,
  preserve: boolean,
) {
  // Canonical IDs are repository-issued; the stable mapping is persisted independently of workspace lease.
  let mappedId = repo.getMetadata(`legacy-canonical:${product.id}`)
  if (!mappedId) {
    const canonical = repo.saveCanonical({ title: product.title })
    mappedId = canonical.id
    repo.setMetadata(`legacy-canonical:${product.id}`, mappedId)
  }
  const oldBindingId = repo.getMetadata(`legacy-binding:${product.id}`)
  const oldBinding = oldBindingId ? repo.getBinding(oldBindingId) : null
  const binding = repo.bindProduct({
    id: oldBinding?.id,
    expectedRevision: oldBinding?.revision,
    canonicalId: mappedId,
    storeId: product.storeId,
    productId: product.productId,
    title: product.title,
  })
  repo.setMetadata(`legacy-binding:${product.id}`, binding.id)
  const factId = `legacy-product-entry:${product.id}`
  const oldFact = repo.getEntry(factId)
  // A stable mapping is needed because new entry IDs are generated by the writer.
  const factMapping = repo.getMetadata(`legacy-fact:${product.id}`)
  const prior = factMapping ? repo.getEntry(factMapping) : oldFact
  const fact = repo.saveDraft({
    id: prior?.id,
    expectedRevision: prior?.revision,
    scope: { kind: 'binding', bindingId: binding.id },
    question: product.title,
    answer:
      [product.description, product.specifications].filter(Boolean).join('\n') || product.title,
    keywords: [product.productId],
    field: 'fact',
    origin: preserve ? 'migration' : 'manual',
  })
  repo.setMetadata(`legacy-fact:${product.id}`, fact.id)
  if (preserve && product.enabled) review(repo, fact, 'legacy-preserved')
  if (product.price) {
    const mapping = repo.getMetadata(`legacy-price:${product.id}`)
    const priorPrice = mapping ? repo.getEntry(mapping) : null
    const price = repo.saveDraft({
      id: priorPrice?.id,
      expectedRevision: priorPrice?.revision,
      scope: { kind: 'binding', bindingId: binding.id },
      question: `${product.title}价格`,
      answer: product.price,
      field: 'price',
      origin: preserve ? 'migration' : 'manual',
      ...(preserve
        ? { expiresAt: product.updatedAt + repo.getSettings().dynamicTtlMinutes * 60000 }
        : {}),
    })
    repo.setMetadata(`legacy-price:${product.id}`, price.id)
    if (preserve && product.enabled) review(repo, price, 'legacy-preserved')
  }
  repo.put('legacy_products', { ...product, enabled: preserve ? product.enabled : false })
  return { canonicalId: mappedId, bindingId: binding.id }
}
export function ingestLegacyIntent(
  repo: KnowledgeRepository,
  pack: LegacyIntentPack,
  preserve: boolean,
  correction = false,
) {
  const cleanEntries = pack.entries.map((entry) =>
    entry.question === auditQuestion ? { ...entry, enabled: false } : entry,
  )
  const next = {
    ...pack,
    enabled: preserve || correction ? pack.enabled : false,
    entries: cleanEntries,
  }
  const activeMappings = new Set<string>()
  const scopes: KnowledgeScope[] = []
  if (pack.productIds.length) {
    // Legacy intent applicability was an explicit store/product predicate, not a Product-row join.
    // Missing identities get their own canonical entity; no same-title or cross-store merge occurs.
    for (const storeId of new Set(pack.storeIds))
      for (const productId of new Set(pack.productIds)) {
        let binding = repo
          .listBindings()
          .find((row) => row.storeId === storeId && row.productId === productId && !row.skuId)
        if (!binding) {
          const canonical = repo.saveCanonical({ title: productId })
          binding = repo.bindProduct({
            canonicalId: canonical.id,
            storeId,
            productId,
            title: productId,
          })
        }
        scopes.push({ kind: 'binding', bindingId: binding.id })
      }
  } else scopes.push({ kind: 'template', storeIds: pack.storeIds })
  for (const [index, entry] of cleanEntries.entries()) {
    if (entry.question === auditQuestion) {
      const sourceId = repo.getMetadata(`legacy-audit:${pack.id}:${index}`)
      const source = sourceId ? repo.getSource(sourceId) : null
      const raw = repo.saveSource({
        id: source?.id,
        expectedRevision: source?.revision,
        kind: 'legacy-audit',
        storeId: pack.storeIds[0] ?? pack.source?.storeId ?? 'unassigned',
        label: `${pack.name} · 来源审计`,
        text: entry.answer,
      })
      repo.setMetadata(`legacy-audit:${pack.id}:${index}`, raw.id)
      continue
    }
    for (const scope of scopes) {
      const key = `legacy-intent-entry:${pack.id}:${index}:${scope.kind === 'binding' ? scope.bindingId : 'template'}`
      activeMappings.add(key)
      const mapped = repo.getMetadata(key)
      const prior = mapped ? repo.getEntry(mapped) : null
      const draft = repo.saveDraft({
        id: prior?.id,
        expectedRevision: prior?.revision,
        scope,
        question: entry.question,
        answer: entry.answer,
        keywords: entry.keywords,
        origin: preserve ? 'migration' : 'manual',
        field: 'fact',
      })
      repo.setMetadata(key, draft.id)
      if ((preserve || correction) && pack.enabled && entry.enabled)
        review(repo, draft, correction ? 'manual-correction' : 'legacy-preserved')
    }
  }
  const mappingKey = `legacy-intent-mappings:${pack.id}`
  const oldMappings = z.array(z.string()).parse(JSON.parse(repo.getMetadata(mappingKey) ?? '[]'))
  for (const key of oldMappings)
    if (!activeMappings.has(key)) {
      const entryId = repo.getMetadata(key),
        old = entryId ? repo.getEntry(entryId) : null
      if (old) repo.withdraw(old.id, old.revision)
    }
  repo.setMetadata(mappingKey, JSON.stringify([...activeMappings]))
  repo.put('legacy_intents', next)
  return next
}
export function createLegacyPorts(repo: KnowledgeRepository) {
  const fallback = <T>(file: string, field: 'items' | 'packs', schema: z.ZodType<T>): T[] => {
    const path = join(repo.directory, file)
    if (!existsSync(path)) return []
    const parsed = z
      .object({ [field]: z.array(schema) })
      .passthrough()
      .parse(JSON.parse(readFileSync(path, 'utf8')))
    return parsed[field] as T[]
  }
  const products = () =>
    repo.readOnly
      ? fallback('product-knowledge.json', 'items', legacyProductSchema)
      : repo.rows<Product>('legacy_products')
  const packs = () =>
    repo.readOnly
      ? fallback('intent-knowledge.json', 'packs', legacyIntentSchema)
      : repo.rows<LegacyIntentPack>('legacy_intents')
  const productRevision = () => Number(repo.getMetadata('legacy-products-revision') ?? 0)
  const intentRevision = () => Number(repo.getMetadata('legacy-intents-revision') ?? 0)
  const parseCsv = (storeId: string, csv: string) => {
    if (typeof csv !== 'string' || Buffer.byteLength(csv) > 1048576) throw Error('CSV最大1MB')
    const parsed = Papa.parse(csv, { header: true, skipEmptyLines: 'greedy' })
    if (
      parsed.errors.length ||
      !parsed.meta.fields?.includes('productId') ||
      !parsed.meta.fields.includes('title')
    )
      throw Error('CSV需要productId、title列且格式完整')
    if (parsed.data.length > 1000) throw Error('每批最多1000个商品')
    const seen = new Set<string>()
    return parsed.data.map((row) => {
      const value = legacyProductInputSchema.parse({
        storeId,
        productId: row.productId,
        title: row.title,
        description: row.description || '',
        specifications: row.specifications || '',
        price: row.price || '',
        enabled: row.enabled !== 'false',
      })
      if (seen.has(value.productId)) throw Error('CSV内商品编号重复')
      seen.add(value.productId)
      return value
    })
  }
  const saveProduct = (input: unknown) =>
    repo.transaction(() => {
      const record = z.record(z.string(), z.unknown()).parse(input)
      const { id, version } = record
      const fields = { ...record }
      for (const key of ['id', 'version', 'updatedAt']) delete fields[key]
      const parsed = legacyProductInputSchema.parse(fields)
      const old = id
        ? products().find((row) => row.id === id && row.storeId === parsed.storeId)
        : null
      if (id && !old) throw Error('商品不存在')
      if (old && old.version !== version) throw Error('商品已更新，请刷新')
      if (
        products().some(
          (row) =>
            row.storeId === parsed.storeId && row.productId === parsed.productId && row.id !== id,
        )
      )
        throw Error('该店铺商品编号已存在')
      const next = legacyProductSchema.parse({
        ...parsed,
        id: old?.id ?? randomUUID(),
        version: (old?.version ?? 0) + 1,
        updatedAt: Date.now(),
        enabled: false,
      })
      ingestLegacyProduct(repo, next, false)
      bump(repo, 'legacy-products-revision')
      return next
    })
  const parseIntents = (json: string) => {
    if (typeof json !== 'string' || Buffer.byteLength(json) > 1048576)
      throw Error('导入文件最大1MB')
    return z.array(legacyIntentInputSchema).max(100).parse(JSON.parse(json))
  }
  const saveIntent = (input: unknown) =>
    repo.transaction(() => {
      const record = z.record(z.string(), z.unknown()).parse(input)
      const { id, version } = record
      const fields = { ...record }
      for (const key of ['id', 'version', 'updatedAt', 'source']) delete fields[key]
      const parsed = legacyIntentInputSchema.parse(fields)
      const old = id ? packs().find((row) => row.id === id) : null
      if (id && !old) throw Error('知识包不存在')
      if (old && old.version !== version) throw Error('知识包已更新，请刷新')
      const next = legacyIntentSchema.parse({
        ...parsed,
        id: old?.id ?? randomUUID(),
        version: (old?.version ?? 0) + 1,
        updatedAt: Date.now(),
        enabled: false,
        ...(old?.source ? { source: old.source } : {}),
      })
      ingestLegacyIntent(repo, next, false)
      bump(repo, 'legacy-intents-revision')
      return next
    })
  return {
    products: {
      summary() {
        const rows = products(),
          byStore: Record<string, number> = {}
        for (const row of rows) byStore[row.storeId] = (byStore[row.storeId] ?? 0) + 1
        return { revision: productRevision(), total: rows.length, byStore }
      },
      identifyTitle(storeId: string, title: string) {
        const rows = products().filter(
          (row) => row.storeId === storeId && row.enabled && row.title === title,
        )
        return rows.length === 1 ? rows[0].productId : ''
      },
      getByProductId(storeId: string, productId: string) {
        return (
          products().find(
            (row) => row.storeId === storeId && row.productId === productId && row.enabled,
          ) ?? null
        )
      },
      list(storeId: string, { offset = 0, limit = 100 }: { offset?: number; limit?: number } = {}) {
        z.number().int().min(0).parse(offset)
        z.number().int().min(1).max(100).parse(limit)
        const rows = products().filter((row) => row.storeId === storeId)
        return {
          revision: productRevision(),
          total: rows.length,
          items: rows.slice(offset, offset + limit),
        }
      },
      save: saveProduct,
      remove(storeId: string, id: string, version: number, confirmed: boolean) {
        return repo.transaction(() => {
          if (confirmed !== true) throw Error('请确认删除商品知识')
          const old = products().find((row) => row.storeId === storeId && row.id === id)
          if (!old) throw Error('商品不存在')
          if (old.version !== version) throw Error('商品已更新，请刷新')
          const bindingId = repo.getMetadata(`legacy-binding:${id}`)
          const binding = bindingId ? repo.getBinding(bindingId) : null
          if (binding?.active) repo.unlinkBinding(binding.id, binding.revision)
          repo.deleteRow('legacy_products', id)
          bump(repo, 'legacy-products-revision')
        })
      },
      search(storeId: string, query: string, limit = 5) {
        const candidates = products().filter(
          (row) =>
            row.storeId === storeId &&
            row.enabled &&
            (query.includes(row.productId) || query.includes(row.title)),
        )
        if (candidates.length !== 1) return []
        const row = candidates[0]
        return repo.resolveKnowledge({
          storeId,
          productId: row.productId,
          query,
          limit: Math.min(10, Math.max(1, limit)),
        }).citations.length
          ? [row]
          : []
      },
      previewImport(storeId: string, csv: string) {
        const items = parseCsv(storeId, csv)
        return {
          revision: productRevision(),
          count: items.length,
          duplicates: items.filter((item) =>
            products().some((row) => row.storeId === storeId && row.productId === item.productId),
          ).length,
          items: items.slice(0, 20),
        }
      },
      importCsv(
        storeId: string,
        csv: string,
        options: { revision?: number; mode?: string; confirmed?: boolean } = {},
      ) {
        return repo.transaction(() => {
          if (options.confirmed !== true) throw Error('请先预览并确认导入')
          if (options.revision !== productRevision()) throw Error('商品已更新，请重新预览')
          if (!['skip', 'replace'].includes(options.mode ?? ''))
            throw Error('请选择重复商品处理方式')
          let imported = 0
          for (const item of parseCsv(storeId, csv)) {
            const old = products().find(
              (row) => row.storeId === storeId && row.productId === item.productId,
            )
            if (old && options.mode === 'skip') continue
            saveProduct({ ...item, id: old?.id, version: old?.version })
            imported++
          }
          return { imported, revision: productRevision() }
        })
      },
      exportCsv(storeId: string) {
        return Papa.unparse(
          products()
            .filter((row) => row.storeId === storeId)
            .map(({ id: _id, version: _version, updatedAt: _updatedAt, ...data }) => data),
          { escapeFormulae: true },
        )
      },
    },
    intents: {
      list: () => packs(),
      summary: () => ({ revision: intentRevision(), total: packs().length }),
      save: saveIntent,
      learnCorrection(input: {
        question: string
        answer: string
        source: z.input<typeof qualitySourceSchema>
      }) {
        return repo.transaction(() => {
          const source = qualitySourceSchema.parse(input.source)
          const parsed = legacyIntentInputSchema.parse({
            name: '人工纠错 · ' + input.question.slice(0, 70),
            enabled: true,
            storeIds: [source.storeId],
            productIds: [],
            entries: [
              { question: input.question, answer: input.answer, keywords: [], enabled: true },
            ],
          })
          const prior = packs().find(
            (pack) =>
              pack.source?.recordId === source.recordId &&
              pack.source.qualityVersion === source.qualityVersion &&
              pack.source.messageTs === source.messageTs &&
              pack.entries[0]?.question === input.question &&
              pack.entries[0]?.answer === input.answer,
          )
          if (prior) return prior
          const next = legacyIntentSchema.parse({
            ...parsed,
            id: randomUUID(),
            version: 1,
            updatedAt: Date.now(),
            source,
          })
          ingestLegacyIntent(repo, next, false, true)
          bump(repo, 'legacy-intents-revision')
          return next
        })
      },
      remove(id: string, version: number, confirmed: boolean) {
        return repo.transaction(() => {
          if (confirmed !== true) throw Error('请确认删除知识包')
          const old = packs().find((row) => row.id === id)
          if (!old) throw Error('知识包不存在')
          if (old.version !== version) throw Error('知识包已更新，请刷新')
          for (const key of z
            .array(z.string())
            .parse(JSON.parse(repo.getMetadata(`legacy-intent-mappings:${id}`) ?? '[]'))) {
            const mapped = repo.getMetadata(key),
              entry = mapped ? repo.getEntry(mapped) : null
            if (entry) repo.withdraw(entry.id, entry.revision)
          }
          repo.deleteRow('legacy_intents', id)
          bump(repo, 'legacy-intents-revision')
        })
      },
      search(storeId: string, query: string, productId = '') {
        const mapping = new Map<string, LegacyIntentPack>()
        for (const pack of packs())
          for (const key of z
            .array(z.string())
            .parse(JSON.parse(repo.getMetadata(`legacy-intent-mappings:${pack.id}`) ?? '[]'))) {
            const entryId = repo.getMetadata(key)
            if (entryId) mapping.set(entryId, pack)
          }
        return repo
          .resolveKnowledge({ storeId, query, productId, limit: 5 })
          .citations.filter((c) => mapping.has(c.entryId))
          .map((c) => ({
            source: 'intent' as const,
            packId: mapping.get(c.entryId)!.id,
            packName: mapping.get(c.entryId)!.name,
            question: c.question,
            answer: c.answer,
          }))
      },
      previewImport(json: string) {
        const rows = parseIntents(json)
        return {
          revision: intentRevision(),
          count: rows.length,
          entries: rows.reduce((count, pack) => count + pack.entries.length, 0),
          packs: rows,
        }
      },
      importJson(json: string, options: { revision?: number; confirmed?: boolean } = {}) {
        return repo.transaction(() => {
          if (options.confirmed !== true) throw Error('请预览并确认导入')
          if (options.revision !== intentRevision()) throw Error('知识包已更新，请重新预览')
          const rows = parseIntents(json)
          for (const row of rows) saveIntent(row)
          return { imported: rows.length }
        })
      },
      exportJson() {
        return JSON.stringify(
          packs().map(
            ({ id: _id, version: _version, updatedAt: _updatedAt, source: _source, ...data }) =>
              data,
          ),
          null,
          2,
        )
      },
    },
  }
}
